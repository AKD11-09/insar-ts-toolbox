def ensure_cluster_field(layer) -> int:
    idx = layer.fields().indexFromName('cluster_id')
    if idx != -1:
        return idx

    fld = QgsField('cluster_id', QVariant.Int)   # modern ctor
    fld.setTypeName('Integer')                   # optional, helps some providers
    fld.setLength(10)
    fld.setPrecision(0)

    with edit(layer):
        ok = layer.dataProvider().addAttributes([fld])
        if not ok:
            raise RuntimeError("Failed to add 'cluster_id' field.")
        layer.updateFields()

    return layer.fields().indexFromName('cluster_id')


