# Rectangle map tool for area selection
class RectangleMapTool(QgsMapTool):
    rectangleSelected = pyqtSignal(QgsRectangle)
    
    def __init__(self, canvas):
        super().__init__(canvas)
        self.canvas = canvas
        self.rubber = None
        self.start = None

    def canvasPressEvent(self, e):
        self.start = self.toMapCoordinates(e.pos())
        if self.rubber:
            self.canvas.scene().removeItem(self.rubber)
        self.rubber = QgsRubberBand(self.canvas, QgsWkbTypes.PolygonGeometry)
        self.rubber.setStrokeColor(QColor(0, 0, 0))
        self.rubber.setFillColor(QColor(0, 0, 0, 0))
        self.rubber.setWidth(2)

    def canvasMoveEvent(self, e):
        if not self.start or not self.rubber:
            return
        end = self.toMapCoordinates(e.pos())
        rect = QgsRectangle(self.start, end)
        self.rubber.setToGeometry(QgsGeometry.fromRect(rect), None)

    def canvasReleaseEvent(self, e):
        if not self.start or not self.rubber:
            return
        end = self.toMapCoordinates(e.pos())
        rect = QgsRectangle(self.start, end)
        self.rectangleSelected.emit(rect)
        self.deactivate()

    def deactivate(self):
        try:
            if self.rubber:
                self.canvas.scene().removeItem(self.rubber)
        except Exception:
            pass
        self.rubber = None
        super().deactivate()

