    def run_clustering(self):
        layer = self.iface.activeLayer()
        if not layer:
            QMessageBox.critical(self.iface.mainWindow(), "Error", "No active layer selected.")
            return
        if layer.geometryType() != QgsWkbTypes.PointGeometry:
            QMessageBox.critical(self.iface.mainWindow(), "Error", "Selected layer is not a point layer.")
            return
        if layer.providerType() == 'delimitedtext':
            QMessageBox.information(self.iface.mainWindow(), "CSV Layer", "CSV detected. Copying to memory layer.")
            mem = QgsVectorLayer(f"Point?crs={layer.crs().authid()}", "Editable Copy", "memory")
            mem.dataProvider().addAttributes(layer.fields()); mem.updateFields()
            mem.dataProvider().addFeatures(list(layer.getFeatures()))
            QgsProject.instance().addMapLayer(mem, addToLegend=True)
            self.iface.setActiveLayer(mem)
            layer = mem

        algo = (self.dlg.comboAlgorithm.currentText() or "").strip().lower()

        selected = [self.dlg.listFeatures.item(i).text()
                    for i in range(self.dlg.listFeatures.count())
                    if self.dlg.listFeatures.item(i).checkState() == Qt.Checked]
        if not selected:
            QMessageBox.warning(self.iface.mainWindow(), "No Features Selected", "Select at least one field.")
            return

        params = {}
        if algo == 'kmeans':
            params['algo'] = 'KMeans'
            params['n_clusters'] = self.dlg.spinKMeansClusters.value()
        elif algo == 'dbscan':
            self.dlg.spinDBSCANeps.interpretText()
            params['algo'] = 'DBSCAN'
            params['eps'] = self.dlg.spinDBSCANeps.value()
            params['min_samples'] = self.dlg.spinDBSCANminPts.value()
        else:
            QMessageBox.critical(self.iface.mainWindow(), "Error", f"Unknown algorithm: {algo}")
            return

        try:
            self.perform_clustering(layer, params, selected)
            idx = layer.fields().indexFromName("cluster_id")
            vals = set(layer.dataProvider().uniqueValues(idx))
            n = len({v for v in vals if v != -1})
            QMessageBox.information(self.iface.mainWindow(), "Clustering Complete",
                                    f"{params['algo']} finished with {n} clusters.")
            self.symbolize_clusters(layer)
        except Exception as e:
            QMessageBox.critical(self.iface.mainWindow(), "Clustering Error", repr(e))

    def perform_clustering(self, layer, params, selected_fields):
        KMeans, DBSCAN, StandardScaler = self._require_sklearn()
        feats = list(layer.getFeatures())

        idxs = [layer.fields().indexFromName(f) for f in selected_fields]
        rows = []
        for ft in feats:
            row = []
            for idx in idxs:
                v = ft[idx]
                try:
                    row.append(float(v))
                except Exception:
                    row.append(np.nan)
            rows.append(row)

        X = np.array(rows, dtype=float)
        X = np.nan_to_num(X, nan=0.0, posinf=0.0, neginf=0.0)
        X = StandardScaler(with_mean=True, with_std=True).fit_transform(X)

        if params['algo'] == 'KMeans':
            model = KMeans(n_clusters=int(params['n_clusters']), n_init=10, random_state=0)
        else:
            model = DBSCAN(eps=float(params['eps']), min_samples=int(params['min_samples']))
        labels = model.fit_predict(X)

        idx = ensure_cluster_field(layer)

        must_commit = False
        if not layer.isEditable():
            layer.startEditing()
            must_commit = True

        try:
            for ft, lab in zip(feats, labels):
                layer.changeAttributeValue(ft.id(), idx, int(lab))
            if must_commit:
                if not layer.commitChanges():
                    layer.rollBack()
                    raise RuntimeError("Commit failed: " + "; ".join(layer.commitErrors()))
        except Exception:
            if must_commit:
                layer.rollBack()
            raise

    def symbolize_clusters(self, layer):
        idx = layer.fields().indexFromName("cluster_id")
        vals = sorted(set(layer.dataProvider().uniqueValues(idx)))
        cats = []
        style = QgsStyle().defaultStyle()
        ramp = style.colorRamp('Spectral') or style.colorRamp('Random colors')

        nvals = max(1, len(vals))
        for i, v in enumerate(vals):
            sym = QgsSymbol.defaultSymbol(layer.geometryType())
            if v == -1:
                sym.setColor(QColor(150, 150, 150))  # noise as gray
            elif ramp and nvals > 1:
                t = 0.0 if nvals == 1 else (i / float(nvals - 1))
                sym.setColor(ramp.color(t))
            label = "Noise (-1)" if v == -1 else f"Cluster {int(v)}"
            cats.append(QgsRendererCategory(v, sym, label))
        layer.setRenderer(QgsCategorizedSymbolRenderer("cluster_id", cats))
        layer.triggerRepaint()

