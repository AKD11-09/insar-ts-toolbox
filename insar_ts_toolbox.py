    def _on_ts_point_picked(self, layer, feature):

        ts_fields = []
        for fld in layer.fields():
            name = fld.name()
            if re.match(r'^\d+', name):
                ts_fields.append(name)

        if not ts_fields:
            QMessageBox.information(self.iface.mainWindow(), "TS Analysis",
                                    "No time-series fields found (fields starting with a date).")
            return

        dates = pd.to_datetime(ts_fields, format='%Y%m%d', errors='coerce')
        keep = ~pd.isna(dates)
        ts_pairs = [(d, n) for d, n, k in zip(dates, ts_fields, keep) if k]
        if not ts_pairs:
            QMessageBox.information(self.iface.mainWindow(), "TS Analysis",
                                    "Fields looked numeric but didn’t parse as YYYYMMDD.")
            return
        ts_pairs.sort(key=lambda x: x[0])

        xs, ys = [], []
        for d, name in ts_pairs:
            try:
                v = feature[name]
            except KeyError:
                continue
            if v is None:
                continue
            try:
                v = float(v)
            except Exception:
                continue
            xs.append(d)
            ys.append(v)

        if len(xs) == 0:
            QMessageBox.information(self.iface.mainWindow(), "TS Analysis",
                                    "Selected feature has no numeric values in the time-series fields.")
            return

        container = getattr(self, 'frameTSPlot', None)
        if container is None:
            QMessageBox.warning(self.iface.mainWindow(), "TS Analysis",
                                "Plot container not found.")
            return

        for c in container.findChildren(QWidget):
            c.setParent(None)
            c.deleteLater()

        canvas = TimeSeriesCanvas(xs, ys, title=f"Time series for ID #{feature.id()} – Displacement")
        container.layout().addWidget(canvas)

        if hasattr(self, 'lblTSInfo') and self.lblTSInfo:
            lyr_name = layer.name() if layer is not None else "—"
            self.lblTSInfo.setText(
                f"Layer: {lyr_name}  •  Feature ID: {feature.id()}  •  {len(xs)} epochs"
            )

        self.dlg.setWindowModality(Qt.NonModal)
        self.dlg.setWindowState(self.dlg.windowState() & ~Qt.WindowMinimized)
        self._render_feature_attributes(layer, feature, title_prefix="Attributes")

        self.dlg.show()
        self.dlg.raise_()
        self.dlg.activateWindow()

    

