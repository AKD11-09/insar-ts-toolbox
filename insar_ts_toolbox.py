    def on_data_properties(self):

        if not self._data_props_show_intro():
            return
        parent = self._ensure_dialog()

        d = LayerAreaDialog(self.iface, parent)
        if not d.exec_():
            return
        layer = d.selectedLayer()
        if layer is None:
            QMessageBox.warning(self.iface.mainWindow(), "Data Properties", "No vector layer selected.")
            return
        roi_needed = d.chkUseROI.isChecked()

        def proceed_with_rect(rect):

            sd = StatsChoiceDialog(layer, parent)
            if not sd.exec_():
                QTimer.singleShot(0, lambda: self._restore_canvas_tool(force_pan=True))
                return

            fields = sd.selected_fields()
            if not fields:
                QMessageBox.information(self.iface.mainWindow(), "Data Properties", "No numeric fields selected.")
                QTimer.singleShot(0, lambda: self._restore_canvas_tool(force_pan=True))
                return
            opts = sd.requested_stats()

            # ROI-aware request
            req = QgsFeatureRequest()
            if rect is not None and layer.geometryType() != QgsWkbTypes.NullGeometry:
                canvas_crs = self.iface.mapCanvas().mapSettings().destinationCrs()
                if layer.crs() != canvas_crs:
                    xform = QgsCoordinateTransform(canvas_crs, layer.crs(), QgsProject.instance())
                    rect = xform.transform(rect)
                req.setFilterRect(rect)

            attr_idx = [layer.fields().indexFromName(f) for f in fields if layer.fields().indexFromName(f) != -1]

            if rect is None and layer.selectedFeatureIds():
                req_sel = QgsFeatureRequest(layer.selectedFeatureIds())
                if attr_idx:
                    req_sel.setSubsetOfAttributes(attr_idx)
                req_sel.setFlags(QgsFeatureRequest.NoGeometry)
                feats = list(layer.getFeatures(req_sel))
            else:
                if attr_idx:
                    req.setSubsetOfAttributes(attr_idx)
                req.setFlags(QgsFeatureRequest.NoGeometry)
                feats = list(layer.getFeatures(req))

            if not feats:
                QMessageBox.information(self.iface.mainWindow(), "Data Properties", "No features in the selected area.")
                QTimer.singleShot(0, lambda: self._restore_canvas_tool(force_pan=True))
                return

            # Compute stats and prep plot data
            stats_per_field = []
            plot_data = []   

            for fname in fields:
                idx = layer.fields().indexFromName(fname)
                if idx == -1:
                    continue

                vals = []
                for ft in feats:
                    v = ft[idx]
                    if v is None:
                        continue
                    try:
                        vals.append(float(v))
                    except Exception:
                        pass
                if not vals:
                    continue

                ss = QgsStatisticalSummary()
                ss.calculate(vals)

                stats_per_field.append(dict(
                    name=fname,
                    count=len(vals),
                    mean=ss.statistic(QgsStatisticalSummary.Mean),
                    median=ss.statistic(QgsStatisticalSummary.Median),
                    std=ss.statistic(QgsStatisticalSummary.StDev),
                    min=ss.statistic(QgsStatisticalSummary.Min),
                    max=ss.statistic(QgsStatisticalSummary.Max),
                ))

                if opts["histogram"]:
                    plot_data.append((fname, vals, int(opts["bins"])))

            if not stats_per_field and not plot_data:
                QMessageBox.information(self.iface.mainWindow(), "Data Properties", "No numeric results to show.")
                QTimer.singleShot(0, lambda: self._restore_canvas_tool(force_pan=True))
                return


            def fmt(x):
                try:
                    return f"{x:.6g}"
                except Exception:
                    return str(x)

            order  = ["count", "mean", "median", "std", "min", "max"]
            labels = {"count": "Count", "mean": "Mean", "median": "Median",
                    "std": "Std. Dev.", "min": "Min", "max": "Max"}
            vals_map = {}
            for fname, vals, bins_used in plot_data:
                vals_map[fname] = (vals, bins_used)

            sections = []
            for s in stats_per_field:
                fname = s["name"]
                html = [
                    "<style>table{border-collapse:collapse;} th,td{border:1px solid #ccc;padding:6px 10px;} th{background:#f5f5f5;text-align:left;}</style>",
                    f"<div class='field-title' style='font-weight:600;font-size:13pt;margin:0 0 6px 0'>{fname}</div>",
                    "<table><tbody>"
                ]
                for k in order:
                    html.append(f"<tr><th>{labels[k]}</th><td>{fmt(s[k])}</td></tr>")
                html.append("</tbody></table>")
                html = "".join(html)

                vals, bins_used = vals_map.get(fname, ([], int(opts["bins"])))
                sections.append({"name": fname, "html": html, "vals": vals, "bins": bins_used})

            if not sections:
                QMessageBox.information(self.iface.mainWindow(), "Data Properties", "No numeric results to show.")
                QTimer.singleShot(0, lambda: self._restore_canvas_tool(force_pan=True))
                return

            dlg2 = DataPropsResultsDialog(parent, "Data Properties (Summary)", sections)
            dlg2.resize(1100, 700)
            dlg2.exec_()

            QTimer.singleShot(0, lambda: self._restore_canvas_tool(force_pan=True))

        if roi_needed:
            canvas = self.iface.mapCanvas()
            self._rectTool = RectangleMapTool(canvas)
            self._prevTool = canvas.mapTool()

            def _finish(rect):
                QTimer.singleShot(0, lambda: self._restore_canvas_tool(force_pan=True))
                proceed_with_rect(rect)

            self._rectTool.rectangleSelected.connect(_finish)
            canvas.setMapTool(self._rectTool)
            self.iface.messageBar().pushInfo("Data Properties", "Draw a rectangle to select the area.")
        else:
            proceed_with_rect(None)