    def _open_url_external(self, url_str: str):

        chrome_path = None
        if os.name == "nt":  # Windows
            # Try PATH first
            chrome_path = shutil.which("chrome") or shutil.which("chrome.exe")
            # Common install locations
            if not chrome_path:
                candidates = [
                    os.path.join(os.environ.get("PROGRAMFILES", ""), "Google", "Chrome", "Application", "chrome.exe"),
                    os.path.join(os.environ.get("PROGRAMFILES(X86)", ""), "Google", "Chrome", "Application", "chrome.exe"),
                    os.path.join(os.environ.get("LOCALAPPDATA", ""), "Google", "Chrome", "Application", "chrome.exe"),
                ]
                chrome_path = next((p for p in candidates if p and os.path.exists(p)), None)

        if chrome_path and os.path.exists(chrome_path):
            # Launch Chrome detached so QGIS isn't blocked
            QProcess.startDetached(chrome_path, [url_str])
            return

        # Non-Windows or Chrome not found → open with default browser
        QDesktopServices.openUrl(QUrl(url_str))


    def _restore_canvas_tool(self, force_pan=False):
        try:
            canvas = self.iface.mapCanvas()
            tool = getattr(self, "_rectTool", None)
            prev = getattr(self, "_prevTool", None)

            if tool is not None:
                try:
                    if canvas.mapTool() is tool:
                        canvas.unsetMapTool(tool)
                except Exception:
                    pass

            if prev is not None and not force_pan:
                try:
                    canvas.setMapTool(prev)
                except Exception:
                    force_pan = True

            if force_pan or prev is None:
                try:
                    self.iface.actionPan().trigger()
                except Exception:
                    pass
        finally:
            self._rectTool = None
            self._prevTool = None
