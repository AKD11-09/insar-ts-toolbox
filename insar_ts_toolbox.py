    # ---------- helpers ----------
    def _apply_distribution(self, i, dist_name):
        c = self.cards[i]
        vals = c["vals"]
        if vals.size < 2:
            return

        if dist_name.lower().startswith("normal"):
            # Fit Normal: mean & std (MLE)
            mu = float(np.mean(vals))
            sigma = float(np.std(vals, ddof=0))
            pdf_x, pdf_y = self._pdf_normal(vals, mu, sigma)
            stats = self._stats_from_normal(vals, mu, sigma)

        elif dist_name.lower().startswith("student") or dist_name.lower().startswith("t"):
            if not self._have_scipy:
                return
            df, loc, scale = self._fit_student_t(vals)
            pdf_x, pdf_y = self._pdf_t(vals, df, loc, scale)
            stats = self._stats_from_t(vals, df, loc, scale)

        elif dist_name.lower().startswith("uniform"):
            pdf_x, pdf_y = self._pdf_uniform(vals)
            stats = self._stats_from_sample(vals)

        elif dist_name.lower().startswith("exponential"):
            pdf_x, pdf_y = self._pdf_exponential(vals)
            stats = self._stats_from_sample(vals)

        elif dist_name.lower().startswith("chi-square"):
            pdf_x, pdf_y = self._pdf_chisquare(vals)
            stats = self._stats_from_sample(vals)

        else:
            return

        # Update left stats HTML
        html = self._stats_to_html(c["name"], stats)
        c["stats"].setHtml(html)

        # Overlay PDF on histogram
        c["canvas"].overlay_pdf(pdf_x, pdf_y)

    def _on_combo_changed(self, _i):
        combo = self.sender()
        if combo is None:
            return
        idx = combo.property("card_index")
        try:
            idx = int(idx)
        except Exception:
            return
        self._apply_distribution(idx, combo.currentText())


    def _stats_to_html(self, fname, d):
        def fmt(x):
            try: return f"{x:.6g}"
            except Exception: return str(x)
        rows = [
            ("Count", d["count"]),
            ("Mean", d["mean"]),
            ("Median", d["median"]),
            ("Std. Dev.", d["std"]),
            ("Min", d["min"]),
            ("Max", d["max"]),
            *([("df (t)", d["df"])] if "df" in d else []),
        ]
        parts = [
            "<style>table{border-collapse:collapse;} th,td{border:1px solid #ccc;padding:6px 10px;} th{background:#f5f5f5;text-align:left;}</style>",
            f"<div class='field-title' style='font-weight:600;font-size:13pt;margin:0 0 6px 0'>{fname}</div>",
            "<table><tbody>"
        ]
        for k, v in rows:
            parts.append(f"<tr><th>{k}</th><td>{fmt(v)}</td></tr>")
        parts.append("</tbody></table>")
        return "".join(parts)

    # -------- Normal --------
    def _pdf_normal(self, vals, mu, sigma):
        x = np.linspace(np.min(vals), np.max(vals), 400)
        if sigma <= 0 or not np.isfinite(sigma):  # avoid divide-by-zero
            y = np.zeros_like(x)
        else:
            y = (1.0 / (np.sqrt(2*np.pi) * sigma)) * np.exp(-0.5*((x - mu)/sigma)**2)
        return x, y

    def _stats_from_normal(self, vals, mu, sigma):
        return dict(
            count=int(vals.size),
            mean=float(mu),
            median=float(mu),     # for Normal, median==mean
            std=float(sigma),
            min=float(np.min(vals)),
            max=float(np.max(vals)),
        )

    # -------- Student-t --------
    def _fit_student_t(self, vals):
        import scipy.stats as st
        # MLE fit: returns (df, loc, scale)
        df, loc, scale = st.t.fit(vals)  # robust for heavier tails
        return float(df), float(loc), float(scale)

    def _pdf_t(self, vals, df, loc, scale):
        import scipy.stats as st
        x = np.linspace(np.min(vals), np.max(vals), 400)
        y = st.t.pdf((x - loc)/scale, df) / scale
        return x, y

    def _stats_from_t(self, vals, df, loc, scale):
        # Theoretical moments (when defined)
        # mean exists if df>1, variance exists if df>2
        mean = loc if df > 1 else np.nan
        var = (df * scale**2)/(df - 2) if df > 2 else np.nan
        std = np.sqrt(var) if np.isfinite(var) else np.nan
        median = loc  # symmetric
        return dict(
            count=int(vals.size),
            mean=float(mean),
            median=float(median),
            std=float(std) if np.isfinite(std) else np.nan,
            min=float(np.min(vals)),
            max=float(np.max(vals)),
            df=float(df),
        )
    def _stats_from_sample(self, vals):
        vals = np.asarray(vals, dtype=float)
        return dict(
            count=int(vals.size),
            mean=float(np.mean(vals)),
            median=float(np.median(vals)),
            std=float(np.std(vals, ddof=0)),
            min=float(np.min(vals)),
            max=float(np.max(vals)),
        )

    def _pdf_uniform(self, vals):
        # U(a,b) with a=min, b=max
        a = float(np.min(vals)); b = float(np.max(vals))
        if not np.isfinite(a) or not np.isfinite(b) or b <= a:
            x = np.linspace(a, a + 1.0, 400); y = np.zeros_like(x)
            return x, y
        x = np.linspace(a, b, 400)
        y = np.full_like(x, 1.0 / (b - a))
        return x, y

    def _pdf_exponential(self, vals):
        v = np.asarray(vals, dtype=float)
        shift = 0.0
        vmin = float(np.min(v))
        if vmin <= 0:
            shift = -vmin + np.finfo(float).eps
            v = v + shift

        try:
            import scipy.stats as st
            params = st.expon.fit(v, floc=0)      
            scale = float(params[-1])
        except Exception:
            m = float(np.mean(v))
            scale = m if (np.isfinite(m) and m > 0) else 1.0

        x_pos = np.linspace(0, np.max(v), 400)
        y_pos = (1.0 / scale) * np.exp(-x_pos / scale)
        x = x_pos - shift
        return x, y_pos

    def _pdf_chisquare(self, vals):
        if not self._have_scipy:
            x = np.linspace(np.min(vals), np.max(vals), 400)
            return x, np.zeros_like(x)
        import scipy.stats as st
        v = np.asarray(vals, dtype=float)
        shift = 0.0
        vmin = float(np.min(v))
        if vmin <= 0:
            shift = -vmin + np.finfo(float).eps
            v = v + shift
        df, loc, scale = st.chi2.fit(v, floc=0)   # fix loc=0
        x_pos = np.linspace(0, np.max(v), 400)
        y_pos = st.chi2.pdf(x_pos, df, loc=0, scale=scale)
        x = x_pos - shift
        return x, y_pos



